# Assignment Operator - It Used to Assign Values to Variables

a = 10
print(a)

# Reassigning the value of a variable
a = 10
a = a+5
a = a+10
print(a)

# Compound Assignment Operator- In this we perform the all arithmetic operation (addition, subtraction, multiplication, division, modulus, exponentiation) and assign the result to the same variable.
a = 10
a +=20
a +=40
a +=60
print(a)

a = 10
a -=20
a -=40
a -=60
print(a)

a = 10
a *=20
a *=40
a *=60
print(a)

a = 10
a /=20
a /=40
a /=60
print(a)

a = 10
a %=20
a %=40
a %=60
print(a)

a = 10
a **=20
a **=40
a **=60
print(a)




