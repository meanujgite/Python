# Comparision Operator

a = 10
b = 20

# Equal to
print(a == b)  # False

# Not equal to
print(a != b)  # True

# Greater than 
print(a > b)  # False

# Less than
print(a < b)  # True

# Greater than or equal to
print(a >= b)  # False

# Less than or equal to
print(a <= b)  # True

print(45 >= 45)  # True

print(23<=52)  # True

print(23<=22)  # False

# By ASCI value

print(ord('A'))  # 65
print(ord('B'))  # 66

print('A' > 'B')  # False

print(ord('a'))  # 97

print('a' > 'A')  # True

print('ABC' < 'abc')  # True

print('abc' < 'ABC')  # False
